  const storageKey = 'zuzu-guide-language-v1';
  const originalText = new WeakMap();
  const originalAttributes = new WeakMap();
  let language = 'en';

  function normalize(value) {
    return value.replace(/\s+/g, ' ').trim();
  }

  function translate(value) {
    return language === 'zh' ? (translations[normalize(value)] || value) : value;
  }

  function translateTextNode(node) {
    if (!originalText.has(node)) originalText.set(node, node.nodeValue);
    const source = originalText.get(node);
    const key = normalize(source);
    if (!key) return;
    const next = language === 'zh' ? translations[key] : null;
    if (!next) {
      node.nodeValue = source;
      return;
    }
    const leading = source.match(/^\s*/)?.[0] || '';
    const trailing = source.match(/\s*$/)?.[0] || '';
    node.nodeValue = `${leading}${next}${trailing}`;
  }

  function translateElementAttributes(element) {
    const attributes = ['aria-label', 'title', 'content'];
    if (!originalAttributes.has(element)) originalAttributes.set(element, {});
    const originals = originalAttributes.get(element);
    attributes.forEach((name) => {
      if (!element.hasAttribute(name)) return;
      if (!(name in originals)) originals[name] = element.getAttribute(name);
      const source = originals[name];
      element.setAttribute(name, language === 'zh' ? (translations[normalize(source)] || source) : source);
    });
  }

  function applyLanguage(nextLanguage, persist = true) {
    language = nextLanguage === 'zh' ? 'zh' : 'en';
    document.documentElement.lang = language === 'zh' ? 'zh-CN' : 'en';

    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
    let node = walker.nextNode();
    while (node) {
      translateTextNode(node);
      node = walker.nextNode();
    }
    document.querySelectorAll('[aria-label], [title], meta[content]').forEach(translateElementAttributes);
    document.title = language === 'zh' ? translations['Zuzu Goes East — Taiwan & China 2026'] : 'Zuzu Goes East — Taiwan & China 2026';
    document.querySelectorAll('[data-language]').forEach((button) => {
      button.setAttribute('aria-pressed', String(button.dataset.language === language));
    });

    if (persist) localStorage.setItem(storageKey, language);
    document.dispatchEvent(new CustomEvent('zuzu:languagechange', { detail: { language } }));
  }

  window.ZUZU_I18N = {
    get language() { return language; },
    setLanguage: applyLanguage,
    t: translate,
    progress(checked, total) {
      return language === 'zh' ? `已打包 ${checked} / ${total} 项` : `${checked} of ${total} packed`;
    }
  };

  document.addEventListener('DOMContentLoaded', () => {
    document.querySelectorAll('[data-language]').forEach((button) => {
      button.addEventListener('click', () => applyLanguage(button.dataset.language));
    });
    const saved = localStorage.getItem(storageKey);
    const preferred = saved || (navigator.language.toLowerCase().startsWith('zh') ? 'zh' : 'en');
    applyLanguage(preferred, Boolean(saved));
  });
